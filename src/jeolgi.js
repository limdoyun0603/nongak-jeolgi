const sum = (terms, t) => terms.reduce((s, [a, b, c]) => s + a * Math.cos(b + c * t), 0);
const DEG = Math.PI / 180;

// ΔT(지구시 - 세계시). 2020년대 약 69초. 연 0.1초 남짓 변하므로 근사로 충분하다.
function deltaT(year) { return 69.2 + 0.1 * (year - 2026); }

// 유닉스 밀리초 → 태양 겉보기 황경(도)
export function sunLongitude(ms) {
  const year = new Date(ms).getUTCFullYear();
  const jde = ms / 86400000 + 2440587.5 + deltaT(year) / 86400;
  const t = (jde - 2451545.0) / 365250; // 율리우스 천년
  const L = (sum(L0, t) + sum(L1, t) * t + sum(L2, t) * t ** 2 + sum(L3, t) * t ** 3 + sum(L4, t) * t ** 4 + sum(L5, t) * t ** 5) / 1e8;
  const R = (sum(R0, t) + sum(R1, t) * t) / 1e8;
  const T = t * 10;
  let lon = L / DEG + 180 - 0.09033 / 3600;
  const om = (125.04452 - 1934.136261 * T) * DEG;
  const Ls = (280.4665 + 36000.7698 * T) * DEG;
  const Lm = (218.3165 + 481267.8813 * T) * DEG;
  const dpsi = (-17.20 * Math.sin(om) - 1.32 * Math.sin(2 * Ls) - 0.23 * Math.sin(2 * Lm) + 0.21 * Math.sin(2 * om)) / 3600;
  lon += dpsi - 20.4898 / 3600 / R;
  return ((lon % 360) + 360) % 360;
}

