const HOUR = 3600000;
const diff = (a, b) => ((a - b) % 360 + 540) % 360 - 180; // a-b를 -180..180으로

// 황경이 target이 되는 시각을 approx 근처에서 찾는다(이분법).
function solveFor(target, approx) {
  let lo = approx - 6 * 24 * HOUR, hi = approx + 6 * 24 * HOUR;
  for (let i = 0; i < 50; i++) {
    const mid = (lo + hi) / 2;
    if (diff(sunLongitude(mid), target) < 0) lo = mid; else hi = mid;
  }
  return Math.round((lo + hi) / 2);
}

const cache = new Map();

// 그 해(양력)에 들어오는 24절기의 절입 시각. [{...term, at}] 시간순.
export function termsOfYear(year) {
  if (cache.has(year)) return cache.get(year);
  const out = [];
  // 태양은 하루 약 0.9856° 움직인다. 1월 1일 황경에서 출발해 다음 15° 경계마다 근사 후 정밀 계산.
  const start = Date.UTC(year, 0, 1) - 9 * HOUR; // 한국 시각 1월 1일 0시
  const end = Date.UTC(year + 1, 0, 1) - 9 * HOUR;
  let lon0 = sunLongitude(start);
  let k = Math.ceil(lon0 / 15) % 24;
  let guess = start + (((k * 15 - lon0) + 360) % 360) / 0.98565 * 24 * HOUR;
  while (guess < end + 10 * 24 * HOUR) {
    const at = solveFor(k * 15, guess);
    if (at >= start && at < end) out.push({ ...TERMS[k], at });
    if (at >= end) break;
    k = (k + 1) % 24;
    guess = at + 15.2 * 24 * HOUR;
  }
  cache.set(year, out);
  return out;
}

// 시각 ms가 속한 절기와 다음 절기, 절기 안에서의 진행도(0..1).
export function termAt(ms) {
  const y = new Date(ms + 9 * HOUR).getUTCFullYear();
  const list = [...termsOfYear(y - 1), ...termsOfYear(y), ...termsOfYear(y + 1)];
  let i = list.findIndex((t, j) => t.at <= ms && (list[j + 1]?.at ?? Infinity) > ms);
  const cur = list[i], next = list[i + 1];
  return { current: cur, next, progress: (ms - cur.at) / (next.at - cur.at), list, position: i };
}
